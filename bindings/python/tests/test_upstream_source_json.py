"""Native capture-source JSON parity over existing literal upstream vectors."""
from __future__ import annotations

import hashlib
import importlib
import json
from pathlib import Path
import unittest

from merlin import upstream as imported_upstream
import merlin.upstream as upstream

ROOT = Path(__file__).resolve().parents[3]
FIXTURE_ROOT = ROOT / "examples/measurements/upstream"
SOURCE_FORMAT = "merlin.upstream.capture-source"
SOURCE_VERSION = 1
MAX_SOURCE_JSON_BYTES = 1024 * 1024
MAX_ORIGINAL_BYTES = 65549
ROOT_OFFSET = 0

# Authored binary golden vectors, not outputs regenerated by a production encoder.
CAPTURE_CASES = (
    ("ucd", "UcdCapture", "from_mac_management", "ucd/minimal.hex"),
    ("ucd", "UcdCapture", "from_mac_management", "ucd/scheduled-50khz.hex"),
    ("rxmer", "RxmerCapture", "from_pnm", "rxmer/ccap-50khz.hex"),
    ("rxmer", "RxmerCapture", "from_pnm", "rxmer/ccap-25khz.hex"),
    ("pre_eq", "PreEqCapture", "from_pnm", "pre-eq/applied.hex"),
    ("pre_eq", "PreEqCapture", "from_pnm", "pre-eq/last-update.hex"),
)
FAMILY_CASES = (CAPTURE_CASES[0], CAPTURE_CASES[2], CAPTURE_CASES[4])
INSPECTION_FORMATS = {
    "ucd": "merlin.upstream.ucd-inspection",
    "rxmer": "merlin.upstream.rxmer-capture",
    "pre_eq": "merlin.upstream.pre-eq-capture",
}


def literal_source(case: tuple[str, str, str, str]) -> bytes:
    """Read unchanged hex octets using the existing upstream fixture convention."""
    return bytes.fromhex((FIXTURE_ROOT / case[3]).read_text())


def envelope(kind: str, source: bytes) -> dict:
    """Construct an independent transport expectation; no capture decoding occurs."""
    return {
        "format": SOURCE_FORMAT,
        "schema_version": SOURCE_VERSION,
        "capture_kind": kind,
        "original_byte_count": len(source),
        "original_sha256": hashlib.sha256(source).hexdigest(),
        "original_bytes": list(source),
    }


def encode(value: dict) -> bytes:
    """Encode test transport without relying on the production source exporter."""
    return json.dumps(value, separators=(",", ":")).encode("utf-8")


class CaptureSourceJsonTests(unittest.TestCase):
    def assert_source_error(self, capture_type, document, code, field) -> None:
        """Check shared categories and root envelope offsets, never message text."""
        with self.assertRaises(upstream.ApiError) as rejected:
            capture_type.from_source_json(document)
        cause = rejected.exception
        self.assertEqual(cause.code, getattr(upstream.ErrorCode, code))
        self.assertEqual(cause.field, "capture_source_json." + field)
        self.assertEqual(cause.offset, ROOT_OFFSET)
        self.assertEqual(cause.engine_code, code)
        self.assertEqual(cause.legacy_code, code)

    def test_existing_public_imports_expose_the_same_native_methods(self) -> None:
        """Existing merlin.upstream import forms retain the same native classes."""
        module = importlib.import_module("merlin.upstream")
        for case in FAMILY_CASES:
            with self.subTest(kind=case[0]):
                capture_type = getattr(upstream, case[1])
                self.assertIs(capture_type, getattr(imported_upstream, case[1]))
                self.assertIs(capture_type, getattr(module, case[1]))
                self.assertEqual(capture_type.__module__, "merlin.upstream")
                self.assertTrue(callable(capture_type.from_source_json))
                capture = capture_type.from_source_json(encode(envelope(case[0], literal_source(case))))
                self.assertIs(type(capture), capture_type)
                self.assertIsInstance(capture.to_source_json(), str)

    def test_literal_envelopes_match_binary_and_unchanged_inspection(self) -> None:
        """Every authored family variant retains identical originals and observations."""
        for case in CAPTURE_CASES:
            with self.subTest(fixture=case[3]):
                source = literal_source(case)
                expected = envelope(case[0], source)
                capture_type = getattr(upstream, case[1])
                baseline = getattr(capture_type, case[2])(source)
                original_inspection = baseline.to_json()
                # Outer JSON spelling/order is deliberately independent of the exporter.
                incoming = json.dumps(expected, indent=2, sort_keys=True).encode("utf-8")
                capture = capture_type.from_source_json(incoming)
                self.assertEqual(capture.original_bytes(), source)
                self.assertEqual(capture.original_sha256(), expected["original_sha256"])
                self.assertEqual(capture.to_json(), original_inspection)
                self.assertEqual(json.loads(capture.to_source_json()), expected)
                self.assertEqual(json.loads(baseline.to_source_json()), expected)
                inspection = json.loads(capture.to_json())
                self.assertEqual(inspection["format"], INSPECTION_FORMATS[case[0]])
                self.assertNotIn("original_bytes", inspection)
                self.assertEqual(baseline.to_json(), original_inspection)
                if case[0] == "rxmer":
                    self.assertEqual(capture.raw_readings(), baseline.raw_readings())
                    self.assertEqual(capture.readings_db(), baseline.readings_db())
                    self.assertEqual(capture.ccap_id_text(), baseline.ccap_id_text())
                    self.assertEqual(capture.pre_eq_enabled(), baseline.pre_eq_enabled())
                elif case[0] == "pre_eq":
                    self.assertEqual(capture.coefficients(), baseline.coefficients())

    def test_roundtrip_results_own_their_binary_bytes_and_observations(self) -> None:
        """Caller/source/capture disposal leaves owned native Python results usable."""
        for case in CAPTURE_CASES:
            with self.subTest(fixture=case[3]):
                source = literal_source(case)
                expected = envelope(case[0], source)
                capture_type = getattr(upstream, case[1])
                binary = getattr(capture_type, case[2])(source)
                source_json = binary.to_source_json()
                inspection_json = binary.to_json()
                del binary
                incoming = source_json.encode("utf-8")
                capture = capture_type.from_source_json(incoming)
                del incoming
                self.assertEqual(capture.to_json(), inspection_json)
                retained_bytes = capture.original_bytes()
                retained_json = capture.to_source_json()
                if case[0] == "rxmer":
                    copied = capture.readings_db()
                    before = capture.readings_db()
                    copied[0] = None
                    self.assertEqual(capture.readings_db(), before)
                elif case[0] == "pre_eq":
                    copied = capture.coefficients()
                    before = capture.coefficients()
                    copied[0] = (0.0, 0.0)
                    self.assertEqual(capture.coefficients(), before)
                del capture
                del source_json
                del source
                self.assertEqual(retained_bytes, bytes(expected["original_bytes"]))
                self.assertEqual(json.loads(retained_json), expected)
                restored = capture_type.from_source_json(retained_json.encode("utf-8"))
                self.assertEqual(restored.to_json(), inspection_json)

    def test_wrong_envelope_fields_reject_without_changing_existing_capture(self) -> None:
        """Format/version/family/count/hash failures use their exact envelope field."""
        for case in FAMILY_CASES:
            capture_type = getattr(upstream, case[1])
            source = literal_source(case)
            baseline = getattr(capture_type, case[2])(source)
            original_inspection = baseline.to_json()
            original_source = baseline.to_source_json()
            expected = envelope(case[0], source)
            wrong_kind = "rxmer" if case[0] == "ucd" else "ucd"
            changes = (
                ("format", "merlin.upstream.inspection", "format"),
                ("schema_version", SOURCE_VERSION + 1, "schema_version"),
                ("capture_kind", wrong_kind, "capture_kind"),
                ("original_byte_count", len(source) + 1, "original_byte_count"),
                ("original_sha256", "0" * len(expected["original_sha256"]), "original_sha256"),
                ("original_sha256", expected["original_sha256"].upper(), "original_sha256"),
                ("original_sha256", expected["original_sha256"][:-1], "original_sha256"),
            )
            for key, value, field in changes:
                with self.subTest(kind=case[0], key=key, value=value):
                    changed = dict(expected)
                    changed[key] = value
                    self.assert_source_error(capture_type, encode(changed), "InvalidInput", field)
                    self.assertEqual(baseline.to_json(), original_inspection)
                    self.assertEqual(baseline.to_source_json(), original_source)
            with self.subTest(kind=case[0], key="payload-hash-mismatch"):
                changed = dict(expected)
                changed["original_bytes"] = list(source)
                changed["original_bytes"][0] ^= 1
                self.assert_source_error(capture_type, encode(changed), "InvalidInput", "original_sha256")

    def test_malformed_duplicate_unknown_and_missing_fields_reject_at_root(self) -> None:
        """Strict JSON transport errors retain InvalidInput/document/offset zero."""
        for case in FAMILY_CASES:
            capture_type = getattr(upstream, case[1])
            expected = envelope(case[0], literal_source(case))
            unknown = dict(expected, observation="must not be accepted")
            missing = dict(expected)
            del missing["original_bytes"]
            duplicate = b'{"format":"duplicate",' + encode(expected)[1:]
            for tag, document in (
                ("syntax", b"{"),
                ("utf8", b"\xff"),
                ("array", b"[]"),
                ("missing-all", b"{}"),
                ("unknown", encode(unknown)),
                ("missing-source", encode(missing)),
                ("duplicate", duplicate),
            ):
                with self.subTest(kind=case[0], invalid=tag):
                    self.assert_source_error(capture_type, document, "InvalidInput", "document")
            for key, value in (
                ("schema_version", "1"),
                ("original_byte_count", -1),
                ("original_bytes", {}),
                ("original_bytes", [256]),
                ("original_bytes", [-1]),
                ("original_bytes", [0.5]),
                ("original_bytes", [True]),
                ("original_bytes", ["0"]),
                ("original_bytes", [None]),
            ):
                with self.subTest(kind=case[0], key=key, invalid=value):
                    changed = dict(expected)
                    changed[key] = value
                    self.assert_source_error(capture_type, encode(changed), "InvalidInput", "document")

    def test_existing_inspection_json_is_never_silently_upgraded_to_source(self) -> None:
        """Old inspection exports remain distinct and cannot invent source octets."""
        for case in CAPTURE_CASES:
            with self.subTest(fixture=case[3]):
                capture_type = getattr(upstream, case[1])
                baseline = getattr(capture_type, case[2])(literal_source(case))
                original = baseline.to_json()
                with self.assertRaises(upstream.ApiError) as rejected:
                    capture_type.from_source_json(original.encode("utf-8"))
                self.assertEqual(rejected.exception.code, upstream.ErrorCode.InvalidInput)
                self.assertTrue(rejected.exception.field.startswith("capture_source_json."))
                self.assertEqual(rejected.exception.offset, ROOT_OFFSET)
                self.assertEqual(baseline.to_json(), original)

    def test_text_limit_exact_and_plus_one_precede_binary_admission(self) -> None:
        """The independent 1 MiB text policy preserves an exact valid envelope."""
        for case in FAMILY_CASES:
            with self.subTest(kind=case[0]):
                capture_type = getattr(upstream, case[1])
                source = literal_source(case)
                incoming = encode(envelope(case[0], source))
                exact = incoming + b" " * (MAX_SOURCE_JSON_BYTES - len(incoming))
                self.assertEqual(len(exact), MAX_SOURCE_JSON_BYTES)
                accepted = capture_type.from_source_json(exact)
                self.assertEqual(accepted.original_bytes(), source)
                self.assert_source_error(capture_type, exact + b" ", "ResourceLimit", "bytes")
                self.assertEqual(accepted.original_bytes(), source)

    def test_original_limit_exact_and_plus_one_preserve_binary_error_ownership(self) -> None:
        """At the source cap the native decoder decides; one extra byte rejects earlier."""
        for case in FAMILY_CASES:
            with self.subTest(kind=case[0]):
                capture_type = getattr(upstream, case[1])
                # Deliberately invalid bytes distinguish envelope admission from decoding.
                exact = bytes(MAX_ORIGINAL_BYTES)
                with self.assertRaises(upstream.ApiError) as binary_rejected:
                    getattr(capture_type, case[2])(exact)
                with self.assertRaises(upstream.ApiError) as json_rejected:
                    capture_type.from_source_json(encode(envelope(case[0], exact)))
                for name in ("code", "field", "offset", "engine_code", "legacy_code"):
                    self.assertEqual(getattr(json_rejected.exception, name), getattr(binary_rejected.exception, name))
                self.assertFalse(json_rejected.exception.field.startswith("capture_source_json."))
                self.assert_source_error(
                    capture_type,
                    encode(envelope(case[0], bytes(MAX_ORIGINAL_BYTES + 1))),
                    "ResourceLimit",
                    "original_bytes",
                )

    def test_underlying_binary_errors_keep_original_categories_fields_offsets(self) -> None:
        """Valid envelopes delegate all original decoder failures without remapping."""
        for case in CAPTURE_CASES:
            capture_type = getattr(upstream, case[1])
            source = literal_source(case)
            unsupported = bytearray(source)
            if case[0] == "ucd":
                unsupported[17] = 4  # Literal unsupported management version vector.
            else:
                unsupported[4] = 0  # Literal unsupported PNM major-version vector.
            for tag, damaged in (("truncated", source[:-1]), ("unsupported", bytes(unsupported))):
                with self.subTest(fixture=case[3], failure=tag):
                    with self.assertRaises(upstream.ApiError) as direct:
                        getattr(capture_type, case[2])(damaged)
                    with self.assertRaises(upstream.ApiError) as imported:
                        capture_type.from_source_json(encode(envelope(case[0], damaged)))
                    for name in ("code", "field", "offset", "engine_code", "legacy_code"):
                        self.assertEqual(getattr(imported.exception, name), getattr(direct.exception, name))
                    self.assertFalse(imported.exception.field.startswith("capture_source_json."))
                    expected_code = upstream.ErrorCode.InvalidInput if tag == "truncated" else upstream.ErrorCode.UnsupportedCapability
                    self.assertEqual(imported.exception.code, expected_code)

    def test_source_import_requires_bytes_and_export_is_owned_text(self) -> None:
        """Python argument conversion stays separate from shared capture failures."""
        for case in FAMILY_CASES:
            with self.subTest(kind=case[0]):
                capture_type = getattr(upstream, case[1])
                document = encode(envelope(case[0], literal_source(case)))
                with self.assertRaises(TypeError):
                    capture_type.from_source_json(document.decode("utf-8"))
                capture = capture_type.from_source_json(document)
                exported = capture.to_source_json()
                self.assertIsInstance(exported, str)
                del capture
                self.assertEqual(json.loads(exported), json.loads(document))


if __name__ == "__main__":
    unittest.main()
