impl RetainedPayload for ChannelPhase {
    /// Counts every owned child beyond the enclosing fixed value.
    ///
    /// # Returns
    /// Complete passive child metadata, or None on checked arithmetic overflow.
    fn retained_children(&self) -> Option<RetainedFootprint> {
        match self {
            Self::Acquisition => Some(RetainedFootprint::default()),
            Self::Observation => Some(RetainedFootprint::default()),
            Self::Completion => Some(RetainedFootprint::default()),
            Self::InterleaverDrain => Some(RetainedFootprint::default()),
            Self::Finished => Some(RetainedFootprint::default()),
            Self::Failed => Some(RetainedFootprint::default()),
        }
    }
}

#[cfg(test)]
mod recovery_tests {
    use super::*;

    #[test]
    fn recovery_never_counts_rejected_or_source_mismatched_words_as_success() {
        // Preserve the independent original Qt five-word classification oracle.
        let mut fec = FecCounters::new();
        fec.record(FecOutcome::Corrected, false);
        fec.record(FecOutcome::Uncorrectable, true);
        fec.record(FecOutcome::Clean, true);
        let before = fec.snapshot();
        let recovery = PayloadRecovery::from_counters(5, &fec, 2);
        let counts = [
            recovery.recovered,
            recovery.rejected,
            recovery.mismatched,
            recovery.unrecovered,
        ];
        assert_eq!(counts, [1, 1, 1, 2]);
        assert_eq!(counts.iter().sum::<u64>(), 5);
        assert_eq!(recovery.generated, 5);
        assert_eq!(fec, before);
    }

    #[test]
    fn empty_and_source_mismatch_counts_do_not_invent_decoder_failures() {
        let mut fec = FecCounters::new();
        assert_eq!(
            serde_json::to_value(PayloadRecovery::from_counters(0, &fec, 0)).unwrap(),
            serde_json::json!({"generated":0,"recovered":0,"rejected":0,"mismatched":0,"unrecovered":0})
        );

        // Both successful decoder categories can disagree with independent source truth.
        fec.record(FecOutcome::Clean, true);
        fec.record(FecOutcome::Corrected, true);
        let recovery = PayloadRecovery::from_counters(3, &fec, 1);
        assert_eq!(recovery.recovered, 0);
        assert_eq!(recovery.rejected, 0);
        assert_eq!(recovery.mismatched, 2);
        assert_eq!(recovery.unrecovered, 1);
        assert_eq!(recovery.generated, 3);
    }
}
